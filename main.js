const question = document.getElementById('question');
const answerbutton = document.getElementById('answer-buttons');
const nextbtn = document.getElementById('next-btn');
let currentQuestionIndex = 0;
let score = 0;

function startQuiz() {
    currentQuestionIndex = 0;
    score = 0;
    showQuestion();
}
function showQuestion() {
    resetState();

    const currentQuestion = lfcQuestions[currentQuestionIndex];
    const questionNo = currentQuestionIndex + 1;

    question.innerHTML = questionNo + ". " + currentQuestion.question;

    currentQuestion.answers.forEach(answer => {
        const btn = document.createElement("button");

        btn.innerHTML = answer.text;
        btn.classList.add("btn");
        btn.dataset.correct = answer.correct;

        btn.addEventListener("click", selectAnswer);

        answerbutton.appendChild(btn);
    });
}

function resetState() {
    nextbtn.style.display = "none";

    while (answerbutton.firstChild) {
        answerbutton.removeChild(answerbutton.firstChild);
    }
}

function showscore() {
    resetState();

    question.innerHTML = `You scored ${score} out of ${lfcQuestions.length}`;

    nextbtn.innerHTML = "Play Again";
    nextbtn.style.display = "block";
}

function selectAnswer(e) {
    const selectedbtn = e.target;
    const isCorrect = selectedbtn.dataset.correct === "true";

    if (isCorrect) {
        selectedbtn.classList.add("correct");
        score++;
    } else {
        selectedbtn.classList.add("incorrect");
    }

    Array.from(answerbutton.children).forEach(btn => {
        if (btn.dataset.correct === "true") {
            btn.classList.add("correct");
        }

        btn.disabled = true;
    });

    nextbtn.style.display = "block";
}

function handlnextbutton() {
    currentQuestionIndex++;

    if (currentQuestionIndex < lfcQuestions.length) {
        showQuestion();
    } else {
        showscore();
    }
}

nextbtn.addEventListener("click", () => {
    if (currentQuestionIndex < lfcQuestions.length - 1) {
        handlnextbutton();
    } else {
        startQuiz();
    }
});
startQuiz();
